#!/usr/bin/env python3
"""Generate src/help_text.rs (long descriptions and examples per command)
from parity/go-help.json and parity/go-help-jini.json, dumps of the Go
command tree's Long/Example with Jini off and on."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((root / "parity/go-help.json").read_text())
dj = json.loads((root / "parity/go-help-jini.json").read_text())
def lit(s):
    return "r#\"" + s + "\"#"
rows = []
for path in sorted(d):
    if not path:
        continue
    v = d[path]
    if v["long"] or v["example"]:
        rows.append(f"    ({lit(path)}, {lit(v['long'])}, {lit(v['example'])}),")
jrows = []
for path in sorted(dj):
    if path and dj[path] != d.get(path):
        v = dj[path]
        jrows.append(f"    ({lit(path)}, {lit(v['long'])}, {lit(v['example'])}),")
out = """// Copyright 2026 Mixlayer Inc. Licensed under Apache-2.0. See LICENSE.
// Generated by parity/gen_help.py from parity/go-help*.json. Do not edit.

//! Long help and examples per command path: (path, long, example).

pub const HELP: &[(&str, &str, &str)] = &[
""" + "\n".join(rows) + """
];

/// Entries that differ when `MIXLAYER_ENABLE_JINI=1`.
pub const HELP_JINI: &[(&str, &str, &str)] = &[
""" + "\n".join(jrows) + """
];

pub fn lookup(path: &str, jini: bool) -> Option<(&'static str, &'static str)> {
    let find = |t: &'static [(&'static str, &'static str, &'static str)]| {
        t.iter().find(|(p, _, _)| *p == path).map(|(_, l, e)| (*l, *e))
    };
    if jini && let Some(hit) = find(HELP_JINI) {
        return Some(hit);
    }
    find(HELP)
}
"""
(root / "src/help_text.rs").write_text(out)
import subprocess
subprocess.run(["rustfmt", "--edition", "2024", str(root / "src/help_text.rs")], check=True, cwd=root)
print(len(rows), "entries")
